/**
 * Builds Marlon Pay for the Worker: stamps the service worker's VERSION with a hash of every precached file (phones
 * update exactly when something changed), then packs public/ into worker/assets.generated.js.
 * Usage: node scripts/build.cjs
 */
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const ROOT = path.join(__dirname, ".."), PUBLIC = path.join(ROOT, "public"), OUT = path.join(ROOT, "worker", "assets.generated.js");
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".json": "application/json",
  ".webmanifest": "application/manifest+json", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8" };
const TEXT = new Set([".html", ".js", ".css", ".json", ".webmanifest", ".svg", ".txt"]);
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

// 1. Service worker version
const SW = path.join(PUBLIC, "sw.js");
const sw = fs.readFileSync(SW, "utf8");
const urls = [.../const PRECACHE = \[([\s\S]*?)\];/.exec(sw)[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
const hash = crypto.createHash("sha256").update(sw.replace(/const VERSION = "[^"]*";/, ""));
for (const u of urls) {
  const f = path.join(PUBLIC, u === "/" ? "index.html" : u.slice(1));
  if (!fs.existsSync(f)) throw new Error(`Precached file is missing: ${u}`);
  hash.update(u + "\0").update(fs.readFileSync(f));
}
const version = hash.digest("hex").slice(0, 12);
const next = sw.replace(/const VERSION = "[^"]*";/, `const VERSION = "${version}";`);
if (next !== sw) fs.writeFileSync(SW, next);

// 2. Pack public/ (headers from public/_headers)
const rules = []; let cur = null;
for (const raw of fs.readFileSync(path.join(PUBLIC, "_headers"), "utf8").split("\n")) {
  if (!raw.trim() || raw.trim().startsWith("#")) continue;
  if (!/^\s/.test(raw)) { cur = { pattern: raw.trim(), headers: {} }; rules.push(cur); continue; }
  const i = raw.indexOf(":"); if (cur && i > 0) cur.headers[raw.slice(0, i).trim()] = raw.slice(i + 1).trim();
}
const files = {}; let total = 0;
for (const file of walk(PUBLIC)) {
  const rel = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  if (path.basename(rel).startsWith("_")) continue;
  const ext = path.extname(rel), buf = fs.readFileSync(file);
  total += buf.length;
  files[rel] = { type: TYPES[ext] || "application/octet-stream", etag: `"${crypto.createHash("sha1").update(buf).digest("hex").slice(0, 20)}"`,
    ...(TEXT.has(ext) ? { text: buf.toString("utf8") } : { b64: buf.toString("base64") }) };
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/build.cjs — do not edit.\nexport const FILES = ${JSON.stringify(files)};\nexport const RULES = ${JSON.stringify(rules)};\n`);
console.log(`sw.js VERSION ${version} (${urls.length} files) · worker/assets.generated.js: ${Object.keys(files).length} files, ${(total / 1024).toFixed(0)} KB`);
