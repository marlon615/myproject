/**
 * Packs public/ into the Worker (worker/assets.generated.js), the same way the Marlon app is deployed: text files as
 * strings, pictures and the video as binary modules. Also turns public/_headers into a header table.
 * (Cloudflare's separate static-file upload can't be used from here, so the Worker serves the files itself.)
 * Usage: node scripts/build-worker.cjs   (npm run build runs build-site.cjs first, then this)
 */
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const ROOT = path.join(__dirname, ".."), PUB = path.join(ROOT, "public");
const TYPES = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".json": "application/json",
  ".webmanifest": "application/manifest+json", ".xml": "application/xml", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml",
  ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".ico": "image/x-icon", ".mp4": "video/mp4",
};
const BINARY = new Set([".png", ".jpg", ".webp", ".ico", ".mp4"]);
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));

const imports = [], entries = [];
let total = 0;
for (const file of walk(PUB).sort()) {
  const rel = "/" + path.relative(PUB, file).split(path.sep).join("/");
  if (rel === "/_headers") continue;
  const ext = path.extname(file).toLowerCase();
  if (!TYPES[ext]) throw new Error(`No content type for ${rel}`);
  const buf = fs.readFileSync(file);
  total += buf.length;
  const etag = `"${crypto.createHash("sha1").update(buf).digest("hex").slice(0, 20)}"`;
  if (BINARY.has(ext)) {
    const name = `bin${imports.length}`;
    imports.push(`import ${name} from ${JSON.stringify(path.relative(path.join(ROOT, "worker"), file).split(path.sep).join("/"))};`);
    entries.push(`  ${JSON.stringify(rel)}: { type: ${JSON.stringify(TYPES[ext])}, etag: ${JSON.stringify(etag)}, data: ${name} },`);
  } else {
    entries.push(`  ${JSON.stringify(rel)}: { type: ${JSON.stringify(TYPES[ext])}, etag: ${JSON.stringify(etag)}, text: ${JSON.stringify(buf.toString("utf8"))} },`);
  }
}

// _headers: "path pattern" lines followed by indented "Name: value" lines.
const rules = [];
let cur = null;
for (const line of fs.readFileSync(path.join(PUB, "_headers"), "utf8").split("\n")) {
  if (!line.trim() || line.trim().startsWith("#")) continue;
  if (!/^\s/.test(line)) { cur = { pattern: line.trim(), headers: {} }; rules.push(cur); continue; }
  const m = line.trim().match(/^([^:]+):\s*(.*)$/);
  if (m && cur) cur.headers[m[1]] = m[2];
}

fs.writeFileSync(path.join(ROOT, "worker", "assets.generated.js"),
  `// Generated by scripts/build-worker.cjs from public/. Don't edit.\n${imports.join("\n")}\nexport const FILES = {\n${entries.join("\n")}\n};\nexport const HEADER_RULES = ${JSON.stringify(rules)};\n`);
console.log(`worker: packed ${entries.length} files (${Math.round(total / 1024)} KB), ${rules.length} header rules`);
