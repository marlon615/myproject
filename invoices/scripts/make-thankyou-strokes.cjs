/**
 * Builds public/lab/thankyou-strokes.js: the words "Thank you" as pen strokes in writing order, for the signing
 * effect test page. Letter shapes come from EMS Allure (single-line script, SIL Open Font License), a derivative of
 * Allura. The letters are joined the way the hand writes them: a connector from each exit into the next letter, and
 * the bowl of "a" and "o" entered with a retrace, so most of each word is one continuous stroke.
 *
 * Usage: node scripts/make-thankyou-strokes.cjs path/to/EMSAllure.svg
 */
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) throw new Error("Usage: node scripts/make-thankyou-strokes.cjs path/to/EMSAllure.svg");
const svg = fs.readFileSync(src, "utf8");
if (!/Font name:\s+EMS Allure/.test(svg) || !/SIL Open Font License/.test(svg)) throw new Error("Expected the EMS Allure SVG font (SIL OFL).");

const glyphs = {};
for (const m of svg.matchAll(/<glyph unicode="([^"]+)"[^>]*?horiz-adv-x="([\d.]+)"(?:[^>]*?\sd="([^"]*)")?/g)) {
  const subpaths = [];
  for (const part of (m[3] || "").split("M").map((s) => s.trim()).filter(Boolean)) {
    const nums = part.replace(/L/g, " ").trim().split(/\s+/).map(Number);
    const pts = [];
    for (let i = 0; i + 1 < nums.length; i += 2) pts.push([nums[i], nums[i + 1]]);
    subpaths.push(pts);
  }
  glyphs[m[1]] = { adv: Number(m[2]), subpaths };
}
for (const c of "Thankyou ") if (!glyphs[c]) throw new Error(`Glyph missing: ${c}`);

const ENTRY = [-31.5, 183]; // every lowercase letter is joined at (−31.5, 183) from the previous letter's exit
const at = (dx) => (p) => [p[0] + dx, p[1]];
/** A gently curved upstroke from a to b (bowing below the straight line, as a hand does). */
function connector(a, b, bow = 0.12) {
  const mx = (a[0] + b[0]) / 2, my = (a[1] + b[1]) / 2;
  const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy);
  const nx = dy / len, ny = -dx / len; // right-hand normal (y up): below the line for an upstroke to the right
  return [[mx + nx * len * bow, my + ny * len * bow]];
}

const G = glyphs;
let x = 0;
const ox = {};
for (const c of ["T", "h", "a", "n", "k", " ", "y", "o", "u"]) { ox[c] = x; x += G[c].adv; }
const total = x;

// 1. T crossbar.
const tBar = G.T.subpaths[0].map(at(ox.T));
// 2. T stem → h → a → n → k (entry, loop and arm): one stroke.
const thank = [];
thank.push(...G.T.subpaths[1].map(at(ox.T)));
const hPts = G.h.subpaths[0].map(at(ox.h));
thank.push(...connector(thank.at(-1), hPts[0]), ...hPts);
// a: enter on the bowl's left side, run up over its top to where the bowl starts, then draw the bowl.
const aRev = [...G.a.subpaths[0]].reverse();                     // writing order: top right, round, stem, exit
const aTop = aRev.slice(0, 5).reverse();                          // the top arc, left to right, ending at the start
thank.push(...[ENTRY, ...aTop.slice(0, 4), ...aRev].map(at(ox.a)));
// n: connector up to the top of the first stroke.
const nPts = G.n.subpaths[0].map(at(ox.n));
thank.push(...connector(thank.at(-1), nPts[0]), ...nPts);
// k: its entry runs straight into the ascender loop, then the arm.
const [kEntry, kLoop, kLeg] = G.k.subpaths;
thank.push(...kEntry.slice(1).map(at(ox.k)), ...kLoop.slice(1).map(at(ox.k)));
// 3. k leg.
const kLegPts = kLeg.map(at(ox.k));
// 4. y → o (entered with a retrace over the top of its bowl).
const you = G.y.subpaths[0].map(at(ox.y));
const [oBowl, oTail] = G.o.subpaths;
const oTop = [oBowl[3], oBowl[2], oBowl[1], oBowl[0]];             // left side up over the top to its start
you.push(...[ENTRY, ...oTop, ...oBowl.slice(1)].map(at(ox.o)));
// 5. o's exit → u.
const tail = oTail.map(at(ox.o));
const uPts = G.u.subpaths[0].map(at(ox.u));
tail.push(...connector(tail.at(-1), uPts[0]), ...uPts);

const strokes = [tBar, thank, kLegPts, you, tail].map((s) => s.map(([px, py]) => [Math.round(px * 10) / 10, Math.round(-py * 10) / 10]));
const all = strokes.flat();
const bounds = {
  minX: Math.min(...all.map((p) => p[0])), maxX: Math.max(...all.map((p) => p[0])),
  minY: Math.min(...all.map((p) => p[1])), maxY: Math.max(...all.map((p) => p[1])),
};

const out = `/**
 * "Thank you" as pen strokes in writing order, for the signing-effect test page.
 * Generated by scripts/make-thankyou-strokes.cjs. Do not edit by hand.
 *
 * Letter shapes: EMS Allure by Sheldon B. Michaels, a single-line derivative of Allura (designer Rob Leuschke,
 * TypeSETit, Copyright (c) 2011 TypeSETit, LLC). Licensed under the SIL Open Font License, Version 1.1
 * (https://openfontlicense.org). The letters are joined here into continuous strokes the way a hand writes them.
 *
 * Units: font units (1000 per em), y pointing down, baseline at y = 0, x-height 300, advance ${total}.
 * Each stroke is a flat list of x, y pairs.
 */
export const STROKES = ${JSON.stringify(strokes.map((s) => s.flat()))};
export const BOUNDS = ${JSON.stringify(bounds)};
export const ADVANCE = ${total};
`;
const dest = path.join(__dirname, "..", "public", "lab", "thankyou-strokes.1.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`${path.relative(process.cwd(), dest)}: ${strokes.length} strokes, ${all.length} points, bounds ${JSON.stringify(bounds)}`);
