/**
 * Packs every file in public/ into worker/assets.generated.js so the Worker can serve the whole app itself
 * (no separate asset upload). Headers from public/_headers are applied per path.
 * Usage: node scripts/build-worker.cjs
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "worker", "assets.generated.js");
const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".json": "application/json", ".webmanifest": "application/manifest+json", ".svg": "image/svg+xml",
  ".png": "image/png", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".js", ".css", ".json", ".webmanifest", ".svg", ".txt"]);

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
  const p = path.join(dir, d.name);
  return d.isDirectory() ? walk(p) : [p];
});

// public/_headers → [{ pattern, headers }]
const rules = [];
let cur = null;
for (const raw of fs.readFileSync(path.join(PUBLIC, "_headers"), "utf8").split("\n")) {
  if (!raw.trim() || raw.trim().startsWith("#")) continue;
  if (!/^\s/.test(raw)) { cur = { pattern: raw.trim(), headers: {} }; rules.push(cur); continue; }
  const i = raw.indexOf(":");
  if (cur && i > 0) cur.headers[raw.slice(0, i).trim()] = raw.slice(i + 1).trim();
}

const files = {};
let total = 0;
for (const file of walk(PUBLIC)) {
  const rel = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  if (path.basename(rel).startsWith("_")) continue; // _headers etc. are config, not content
  const ext = path.extname(rel);
  const buf = fs.readFileSync(file);
  total += buf.length;
  files[rel] = {
    type: TYPES[ext] || "application/octet-stream",
    etag: `"${crypto.createHash("sha1").update(buf).digest("hex").slice(0, 20)}"`,
    ...(TEXT.has(ext) ? { text: buf.toString("utf8") } : { b64: buf.toString("base64") }),
  };
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/build-worker.cjs — do not edit.\nexport const FILES = ${JSON.stringify(files)};\nexport const RULES = ${JSON.stringify(rules)};\n`);
console.log(`worker/assets.generated.js: ${Object.keys(files).length} files, ${(total / 1024).toFixed(0)} KB`);
